/**
 * Writes one FHIR Connect mapping and asks openFHIR to re-read its bootstrap directory.
 *
 * A mapping openFHIR rejects is still written — the answer says what went wrong, and seeing that
 * is the reason the editor exists.
 */
export async function saveMapping(file: string, content: string): Promise<SaveResult> {
  const response = await fetch(`/api/mappings/${encodeURIComponent(file)}`, {
    method: 'POST',
    headers: headers({ 'Content-Type': 'text/plain' }),
    body: content,
  });
  if (!response.ok) throw failure(response, 'Saving the mapping');
  return response.json() as Promise<SaveResult>;
}

