/** Calls to the Gradle backend. Vite proxies these to :18080 in development. */

/**
 * Every request says which language it wants. The backend generates most of the teaching text —
 * the pipeline stages, what each mapping did — and resolves `Accept-Language` per request, so this
 * is what keeps its prose and the frontend's in the same language.
 */
function headers(extra: Record<string, string> = {}): Record<string, string> {
  return { 'Accept-Language': language(), ...extra };
}

/**
 * Names the patient a request is about.
 *
 * Clinical reads and writes are scoped to one record; the backend turns the id into an EHR id by
 * asking openEHR. Before the directory has loaded there is nothing to send, and the backend then
 * falls back to its configured default rather than failing.
 */
function withPatient(url: string): string {
  const id = patient();
  if (!id) return url;
  return `${url}${url.includes('?') ? '&' : '?'}patient=${encodeURIComponent(id)}`;
}

/**
 * A 404 on an endpoint the frontend knows about almost always means one thing: the backend running
 * on :18080 was started before this endpoint existed. Saying so beats making someone wonder whether
 * their data is missing.
 */
function failure(response: Response, what: string): Error {
  if (response.status === 404) {
    return new Error(
      `${what} is not available (HTTP 404) — the backend is running an older build. ` +
        'Restart it with `cd backend && ./gradlew bootRun`.',
    );
  }
  return new Error(`${what} failed (HTTP ${response.status})`);
}

export async function fetchSeries(days = 30): Promise<HeartRateSeries> {
  // no-store because this is reloaded straight after a write: a cached copy would show the value
  // that was just corrected and look exactly like a correction that did not take.
  const response = await fetch(withPatient(`/api/heart-rate?days=${days}`), {
    cache: 'no-store',
    headers: headers(),
  });
  if (!response.ok) throw new Error(`Could not load heart rate data (HTTP ${response.status})`);
  return response.json() as Promise<HeartRateSeries>;
}

/**
 * True when the backend is older than this page — it does not know an endpoint the page needs.
 *
 * <p>The backend runs on the host while the frontend runs in a container, so restarting one and not
 * the other is easy, and the symptoms are misleading: corrections that never appear, empty tabs.
 */
export async function backendIsCurrent(): Promise<boolean> {
  try {
    const response = await fetch('/api/about', { cache: 'no-store', headers: headers() });
    if (!response.ok) return false;
    const about = (await response.json()) as { capabilities?: string[] };
    return (about.capabilities ?? []).includes('composition-versioning');
  } catch {
    // Unreachable is a different problem, with its own message on the chart.
    return true;
  }
}

/**
 * Sends a FHIR Bundle to the import endpoint. Answers with an OperationOutcome saying what went
 * in and what did not.
 */
export async function importFile(json: string): Promise<OperationOutcome> {
  const response = await fetch(withPatient('/fhir/Bundle'), {
    method: 'POST',
    headers: headers({ 'Content-Type': 'application/json' }),
    body: json,
  });
  const body = (await response.json().catch(() => null)) as OperationOutcome | null;
  if (!body || body.resourceType !== 'OperationOutcome') {
    throw new Error(`The import failed (HTTP ${response.status})`);
  }
  return body;
}

/**
 * A month of made-up readings as a FHIR Bundle, ending today. Generated by the backend on every
 * call rather than checked in, so it cannot fall out of the chart's 30-day window.
 */
export async function fetchSampleBundle(days = 30): Promise<string> {
  const response = await fetch(withPatient(`/fhir/Bundle/$sample?days=${days}`), {
    cache: 'no-store',
    headers: headers(),
  });
  if (!response.ok) throw failure(response, 'The sample data');
  return response.text();
}

